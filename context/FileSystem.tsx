export interface FileNode {
  name: string;
  type: "file" | "folder";
  content?: string;
  children?: FileNode[];
  progress?: number;
}

interface FileSystemContextProps {
  files: FileNode[];
  setFiles: React.Dispatch<React.SetStateAction<FileNode[]>>;
  addFile: (
    parentPath: string[],
    name: string,
    type: "file" | "folder",
    content?: string
  ) => Promise<boolean>;
  updateFile: (path: string[], updatedContent: string) => void;
  deleteFile: (path: string[]) => void;
  renameFile: (path: string[], newName: string) => void;
  moveFile: (sourcePath: string[], destinationPath: string[]) => void;
  copyFile: (sourcePath: string[], destinationPath: string[]) => void;
  pasteFiles: (
    clipboardItems: { type: "copy" | "cut"; items: string[] },
    destinationPath: string[]
  ) => void;
  getFile: (path: string[]) => FileNode | null;
  searchFiles: (query: string) => FileNode[];
  updateFileProgress: (path: string[], progress: number) => void;
}

const FileSystemContext = createContext<FileSystemContextProps | null>(null);

export const useFileSystem = () => {
  const context = useContext(FileSystemContext);
  if (!context) {
    throw new Error("useFileSystem must be used within a FileSystemProvider");
  }
  return context;
};

