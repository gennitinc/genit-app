export const FileSystemProvider: React.FC<{ children: React.ReactNode }> = ({
  children,
}) => {
  const {
    messages,
    setMessages,
    setVersions,
    chat,
    setChat,
    versions,
    sendMessage,
    fetchVersions,
    isTyping,
    handleTyping,
  } = useChat();
  const [files, setFiles] = useState<FileNode[]>([]);

  useEffect(() => {
    const aiMessages = messages.filter((message: any) => message.type === "ai");

    if (aiMessages.length === 0) return;

    let lastValidAIMsg = null;

    for (let i = aiMessages.length - 1; i >= 0; i--) {
      let currentMsg = aiMessages[i];

      try {
        const confirmedMessage =
          typeof currentMsg === "string" ? JSON.parse(currentMsg) : currentMsg;

        if (
          confirmedMessage.content &&
          typeof confirmedMessage.content === "string"
        ) {
          confirmedMessage.content = JSON.parse(confirmedMessage.content);
        }

        if (
          Array.isArray(confirmedMessage.content?.generatedFiles) &&
          confirmedMessage.content.generatedFiles.length > 0
        ) {
          lastValidAIMsg = confirmedMessage;
          break; // Stop at the most recent valid message
        }
      } catch (error) {
        console.error("Error parsing AI message content:", error);
      }
    }

    if (lastValidAIMsg) {
      console.log("Displaying Last Valid AI Message:", lastValidAIMsg);

      // Set the non-empty generated files
      setFiles(lastValidAIMsg.content.generatedFiles);

      // Log responseText and codeBlock safely
      if (lastValidAIMsg.content?.responseText) {
        console.log(
          "Response Text:",
          typeof lastValidAIMsg.content.responseText === "string"
            ? lastValidAIMsg.content.responseText
            : JSON.stringify(lastValidAIMsg.content.responseText, null, 2)
        );
      }

      if (lastValidAIMsg.content?.codeBlock) {
        console.log(
          "Code Block:",
          typeof lastValidAIMsg.content.codeBlock === "string"
            ? lastValidAIMsg.content.codeBlock
            : JSON.stringify(lastValidAIMsg.content.codeBlock, null, 2)
        );
      }
    } else {
      console.warn("No AI message found with non-empty generatedFiles.");
    }
  }, [messages]);

  const getNodeAtPath = useCallback(
    (path: string[], nodes: FileNode[]): FileNode | null => {
      if (path.length === 0) return null;
      const [current, ...rest] = path;
      const foundNode = nodes.find((node) => node.name === current);
      if (!foundNode) return null;
      if (rest.length === 0) return foundNode;
      if (foundNode.type === "folder" && foundNode.children) {
        return getNodeAtPath(rest, foundNode.children);
      }
      return null;
    },
    []
  );

  const updateNodeAtPath = useCallback(
    (
      path: string[],
      nodes: FileNode[],
      updater: (node: FileNode) => FileNode
    ): FileNode[] => {
      if (path.length === 0) return nodes;
      const [current, ...rest] = path;
      return nodes.map((node) => {
        if (node.name !== current) return node;
        if (rest.length === 0) return updater(node);
        if (node.type === "folder" && node.children) {
          return {
            ...node,
            children: updateNodeAtPath(rest, node.children, updater),
          };
        }
        return node;
      });
    },
    []
  );

  const addFile = useCallback(
    (
      parentPath: string[],
      name: string,
      type: "file" | "folder",
      content = ""
    ) => {
      return new Promise<boolean>((resolve) => {
        setFiles((prevFiles) => {
          const newFiles = [...prevFiles];
          const parent = getNodeAtPath(parentPath, newFiles);
          if (parent && parent.type === "folder") {
            if (!parent.children) parent.children = [];
            // Check if a file/folder with the same name already exists
            const existingItem = parent.children.find(
              (child) => child.name === name
            );
            if (!existingItem) {
              parent.children.push({
                name,
                type,
                content,
                children: type === "folder" ? [] : undefined,
              });
              resolve(true);
            }
          } else {
            resolve(false);
          }
          return newFiles;
        });
      });
    },
    [getNodeAtPath]
  );

  const updateFile = useCallback(
    (path: string[], updatedContent: string) => {
      setFiles((prevFiles) =>
        updateNodeAtPath(path, prevFiles, (node) => ({
          ...node,
          content: updatedContent,
        }))
      );
    },
    [updateNodeAtPath]
  );

  const deleteFile = useCallback(
    (path: string[]): void => {
      setFiles((prevFiles) => {
        const parentPath = path.slice(0, -1);
        const fileName = path[path.length - 1];
        const updatedFiles = updateNodeAtPath(
          parentPath,
          prevFiles,
          (node) => ({
            ...node,
            children: node.children?.filter((child) => child.name !== fileName),
          })
        );
        return updatedFiles;
      });
    },
    [updateNodeAtPath]
  );

  const renameFile = useCallback(
    (path: string[], newName: string) => {
      setFiles((prevFiles) =>
        updateNodeAtPath(path, prevFiles, (node) => ({
          ...node,
          name: newName,
        }))
      );
    },
    [updateNodeAtPath]
  );

  const moveFile = useCallback(
    (sourcePath: string[], destinationPath: string[]) => {
      setFiles((prevFiles) => {
        const sourceNode = getNodeAtPath(sourcePath, prevFiles);
        if (!sourceNode) return prevFiles;

        // Remove the file from its original location
        let updatedFiles = updateNodeAtPath(
          sourcePath.slice(0, -1),
          prevFiles,
          (node) => ({
            ...node,
            children: node.children?.filter(
              (child) => child.name !== sourcePath[sourcePath.length - 1]
            ),
          })
        );

        // Add the file to the new location
        updatedFiles = updateNodeAtPath(
          destinationPath,
          updatedFiles,
          (node) => ({
            ...node,
            children: [...(node.children || []), sourceNode],
          })
        );

        return updatedFiles;
      });
    },
    [getNodeAtPath, updateNodeAtPath]
  );

  const copyFile = useCallback(
    (sourcePath: string[], destinationPath: string[]) => {
      setFiles((prevFiles) => {
        const sourceNode = getNodeAtPath(sourcePath, prevFiles);
        if (!sourceNode) return prevFiles;

        const copiedNode = JSON.parse(JSON.stringify(sourceNode)); // Deep copy
        return updateNodeAtPath(destinationPath, prevFiles, (node) => ({
          ...node,
          children: [...(node.children || []), copiedNode],
        }));
      });
    },
    [getNodeAtPath, updateNodeAtPath]
  );

  const pasteFiles = useCallback(
    (
      clipboardItems: { type: "copy" | "cut"; items: string[] },
      destinationPath: string[]
    ) => {
      setFiles((prevFiles) => {
        let updatedFiles = [...prevFiles];

        clipboardItems.items.forEach((item) => {
          const sourcePath = item.split("/");
          const sourceNode = getNodeAtPath(sourcePath, updatedFiles);

          if (sourceNode) {
            if (clipboardItems.type === "copy") {
              const copiedNode = JSON.parse(JSON.stringify(sourceNode)); // Deep copy
              updatedFiles = updateNodeAtPath(
                destinationPath,
                updatedFiles,
                (node) => ({
                  ...node,
                  children: [...(node.children || []), copiedNode],
                })
              );
            } else {
              // Cut operation
              updatedFiles = updateNodeAtPath(
                sourcePath.slice(0, -1),
                updatedFiles,
                (node) => ({
                  ...node,
                  children: node.children?.filter(
                    (child) => child.name !== sourcePath[sourcePath.length - 1]
                  ),
                })
              );

              updatedFiles = updateNodeAtPath(
                destinationPath,
                updatedFiles,
                (node) => ({
                  ...node,
                  children: [...(node.children || []), sourceNode],
                })
              );
            }
          }
        });

        return updatedFiles;
      });
    },
    [getNodeAtPath, updateNodeAtPath]
  );

  const getFile = useCallback(
    (path: string[]) => {
      return getNodeAtPath(path, files);
    },
    [getNodeAtPath, files]
  );

  const searchFiles = useCallback(
    (query: string): FileNode[] => {
      const searchRecursive = (nodes: FileNode[]): FileNode[] => {
        return nodes.flatMap((node) => {
          if (node.name.toLowerCase().includes(query.toLowerCase())) {
            return [node];
          }
          if (node.type === "folder" && node.children) {
            return searchRecursive(node.children);
          }
          return [];
        });
      };
      return searchRecursive(files);
    },
    [files]
  );

  const updateFileProgress = useCallback(
    (path: string[], progress: number) => {
      setFiles((prevFiles) =>
        updateNodeAtPath(path, prevFiles, (node) => ({
          ...node,
          progress,
        }))
      );
    },
    [updateNodeAtPath]
  );

  return (
    <FileSystemContext.Provider
      value={{
        files,
        setFiles,
        addFile,
        updateFile,
        deleteFile,
        renameFile,
        moveFile,
        copyFile,
        pasteFiles,
        getFile,
        searchFiles,
        updateFileProgress,
      }}
    >
      {children}
    </FileSystemContext.Provider>
  );
};
